#!/bin/sh
# Regenerates THIRD_PARTY_NOTICES: the license, notice and patent files of
# every Go module linked into the gitbackup binary, plus the Go standard
# library's license. Run it from the repository root inside the Go image:
#
#   docker run --rm -v "$PWD:/src" -v gomod-cache:/go/pkg/mod -w /src \
#     golang:1.27-alpine sh contrib/gen-notices.sh
set -eu
out=${1:-THIRD_PARTY_NOTICES}
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
	echo "Third-party notices for the gitbackup binary"
	echo "============================================="
	echo
	echo "The gitbackup binary is built from the Go modules listed below and the Go"
	echo "standard library. Their license, notice and patent files follow verbatim."
	echo "Generated by contrib/gen-notices.sh – do not edit by hand."
	echo
	echo "Modules:"
	echo "  Go standard library $(go env GOVERSION)"
	go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/gitbackup | sort -u | sed 's/^/  /'

	section() { # <title> <file>
		echo
		echo
		echo "--------------------------------------------------------------------------------"
		echo "$1"
		echo "--------------------------------------------------------------------------------"
		echo
		cat "$2"
	}
	section "Go standard library $(go env GOVERSION) – LICENSE" "$(go env GOROOT)/LICENSE"
	[ -f "$(go env GOROOT)/PATENTS" ] && section "Go standard library $(go env GOVERSION) – PATENTS" "$(go env GOROOT)/PATENTS"

	go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/gitbackup | sort -u |
		while read -r path version dir; do
			found=0
			for f in $(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \) | sort); do
				section "$path $version – $(basename "$f")" "$f"
				found=1
			done
			if [ $found = 0 ]; then
				echo "no license file found for $path $version" >&2
				exit 1
			fi
		done
} > "$tmp"
chmod 644 "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out" >&2
